#!/usr/bin/env node
/*
 * Updates the PK Sample (data/pk-sample.js): the profile "Start from the PK Sample" copies into a
 * new account.
 *
 * The sample used to be read live from the "payton" cloud account at the moment a newcomer picked
 * it. Any name can be signed into, so whoever last signed in as payton decided what every new
 * account started from. It is a committed file now, and this script is the way to change it:
 *
 *   node scripts/update-pk-sample.js omni-ledger-profile.json   # a file from the app's Export button
 *   node scripts/update-pk-sample.js --from-cloud                # straight from the "payton" account
 *   node scripts/update-pk-sample.js --from-cloud <handle>       # ...or another account
 *   add --dry-run to see what would change without writing anything
 *
 * Only the taste profile is copied -- tiers, owned titles, ratings, boosts -- exactly what the live
 * fetch used to copy. Not the Up Next / Completed list, theme or layout.
 *
 * Before writing, every title id is checked against the corpus. An unknown id is refused rather
 * than written, since it would silently be missing from a newcomer's sample; --drop-unknown removes
 * them (and lists each one). A profile with nothing tiered or owned is refused too: that is what a
 * wiped account looks like, and it is never what the sample should become. What changed is printed
 * by title, so it can be read before committing.
 */

'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SAMPLE_FILE = path.join(ROOT, 'data', 'pk-sample.js');
const DEFAULT_HANDLE = 'payton';

// Every profile field that names titles. `list` is an array of ids, `keys` an object keyed by id.
const ID_FIELDS = [
  { key: 'declaredGoatIds', label: 'Gold', shape: 'list' },
  { key: 'silverTierIds', label: 'Silver', shape: 'list' },
  { key: 'bronzeTierIds', label: 'Bronze', shape: 'list' },
  { key: 'ownedMedia', label: 'Owned films & TV', shape: 'keys' },
  { key: 'ownedBooksExtra', label: 'Owned books', shape: 'keys' },
  { key: 'ownedGameIds', label: 'Owned games', shape: 'list' },
  { key: 'ratings', label: 'Ratings', shape: 'keys' },
  { key: 'cosmicHorrorDeclaredIds', label: 'Cosmic Horror picks', shape: 'list' },
  { key: 'cosmicHorrorCanon', label: 'Cosmic Horror canon', shape: 'keys' },
  { key: 'watchlist', label: 'Contenders watchlist', shape: 'keys' },
];
const TASTE_FIELDS = ['declaredGoatIds', 'silverTierIds', 'bronzeTierIds', 'ownedMedia', 'ownedBooksExtra', 'ownedGameIds'];

function idsOf(profile, field) {
  const v = profile && profile[field.key];
  if (field.shape === 'list') return Array.isArray(v) ? v.map(String) : [];
  return v && typeof v === 'object' && !Array.isArray(v) ? Object.keys(v) : [];
}

// What the app counts as held for a field. The one difference from idsOf: books numbered at or
// below ownedBookIdCeiling are owned too -- a legacy rule the app still honours (see
// OWNED_BOOK_ID_CEILING in app/ledger-app.js), so leaving it out would report owned books as removed.
function heldIds(profile, field, titles) {
  const ids = new Set(idsOf(profile, field));
  const ceiling = field.key === 'ownedBooksExtra' ? Number(profile && profile.ownedBookIdCeiling) || 0 : 0;
  if (ceiling) for (const id of titles.keys()) if (/^b\d+$/.test(id) && parseInt(id.slice(1), 10) <= ceiling) ids.add(id);
  return ids;
}

// id -> title, across the four media and the contenders, read the way validate-corpus.js reads them.
function loadTitles() {
  const titles = new Map();
  for (const [file, varName] of [['movies.js', 'movies'], ['tv.js', 'tvShows'], ['games.js', 'videoGames'],
    ['books.js', 'books'], ['contenders.js', 'contenders']]) {
    const src = fs.readFileSync(path.join(ROOT, 'data', file), 'utf8');
    for (const r of new Function(src + '\nreturn ' + varName + ';')()) titles.set(String(r.id), r.title);
  }
  return titles;
}

function unknownIds(profile, titles) {
  const out = [];
  for (const f of ID_FIELDS) for (const id of idsOf(profile, f)) if (!titles.has(id)) out.push({ field: f, id });
  return out;
}

function readSampleFile(file) {
  const src = fs.readFileSync(file || SAMPLE_FILE, 'utf8');
  return new Function(src + '\nreturn PK_SAMPLE_PROFILE;')();
}

function renderSampleFile(profile, source) {
  return [
    '// The PK Sample: the profile "Start from the PK Sample" copies into a new account.',
    '//',
    '// A fixed copy on purpose. It used to be read live from the "payton" cloud account, and since any',
    '// name can be signed into, whoever last signed in as payton decided what every newcomer started',
    '// from. It only changes through a commit now.',
    '//',
    '// Generated by scripts/update-pk-sample.js -- change it through that rather than by hand: it checks',
    '// every title id against the corpus and prints what changed.',
    '// Source: ' + source,
    'const PK_SAMPLE_PROFILE=' + JSON.stringify(profile, null, 1) + ';',
    '',
  ].join('\n');
}

function describeChanges(before, after, titles) {
  const name = id => (titles.get(id) || '(unknown title)') + ' [' + id + ']';
  const lines = [];
  for (const f of ID_FIELDS) {
    const a = heldIds(before, f, titles), b = heldIds(after, f, titles);
    const added = [...b].filter(id => !a.has(id)), removed = [...a].filter(id => !b.has(id));
    let changed = [];
    if (f.shape === 'keys' && before && after && before[f.key] && after[f.key]) {
      changed = [...b].filter(id => id in before[f.key] && id in after[f.key] &&
        JSON.stringify(before[f.key][id]) !== JSON.stringify(after[f.key][id]));
    }
    lines.push('  ' + f.label.padEnd(22) + String(b.size).padStart(4) +
      (added.length || removed.length || changed.length
        ? '   (+' + added.length + ' / -' + removed.length + (changed.length ? ' / ' + changed.length + ' changed' : '') + ')'
        : '   (no change)'));
    for (const id of added.slice(0, 15)) lines.push('      + ' + name(id));
    for (const id of removed.slice(0, 15)) lines.push('      - ' + name(id));
    for (const id of changed.slice(0, 15)) {
      lines.push('      ~ ' + name(id) + ': ' + JSON.stringify(before[f.key][id]) + ' -> ' + JSON.stringify(after[f.key][id]));
    }
    const hidden = Math.max(0, added.length - 15) + Math.max(0, removed.length - 15) + Math.max(0, changed.length - 15);
    if (hidden) lines.push('      ...and ' + hidden + ' more');
  }
  const other = Object.keys(Object.assign({}, before, after))
    .filter(k => !ID_FIELDS.some(f => f.key === k))
    .filter(k => JSON.stringify((before || {})[k]) !== JSON.stringify((after || {})[k]));
  lines.push('  Other settings changed: ' + (other.length ? other.join(', ') : 'none'));
  return lines;
}

// The app's Export writes {version, exported, profile, watchlist, theme, density}; an older export,
// or PROFILE_TEMPLATE.md, is the bare profile. Same detection as applyImportedSnapshot() in the app.
function profileFromFile(file) {
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error(file + ' is not a profile object');
  const isSnapshot = parsed.profile && typeof parsed.profile === 'object' && !Array.isArray(parsed.profile);
  return { profile: isSnapshot ? parsed.profile : parsed, source: 'the file ' + path.basename(file) };
}

async function profileFromCloud(handle) {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const m = html.match(/var SUPABASE_CONFIG=\{url:"([^"]+)",anonKey:"([^"]+)"\}/);
  if (!m || m[2].indexOf('PASTE_YOUR') === 0) throw new Error('cloud accounts are not configured in index.html');
  const [, url, key] = m;
  const res = await fetch(url + '/rest/v1/profiles?select=data,updated_at&handle=eq.' + encodeURIComponent(handle),
    { headers: { apikey: key, Authorization: 'Bearer ' + key } });
  if (!res.ok) throw new Error('Supabase answered ' + res.status + ' ' + (await res.text()).slice(0, 200));
  const rows = await res.json();
  const raw = rows[0] && rows[0].data && rows[0].data.omniLedgerProfile;
  if (!raw) throw new Error('no saved profile for "' + handle + '"');
  return { profile: JSON.parse(raw), source: 'the "' + handle + '" account, last saved ' + rows[0].updated_at };
}

async function main() {
  const argv = process.argv.slice(2);
  const flag = f => argv.includes(f);
  const positional = argv.filter(a => !a.startsWith('--'));
  const fromCloud = flag('--from-cloud');
  if (!fromCloud && positional.length !== 1) {
    console.error('usage: update-pk-sample.js <exported-profile.json> [--dry-run] [--drop-unknown]\n' +
                  '       update-pk-sample.js --from-cloud [handle] [--dry-run] [--drop-unknown]');
    process.exit(2);
  }
  const got = fromCloud ? await profileFromCloud(positional[0] || DEFAULT_HANDLE) : profileFromFile(positional[0]);
  const profile = JSON.parse(JSON.stringify(got.profile));
  // The app adds this to the copy it makes; the sample itself should not carry it.
  delete profile.pkSampleOrigin;

  if (!TASTE_FIELDS.some(k => idsOf(profile, ID_FIELDS.find(f => f.key === k)).length)) {
    console.error('Refusing: this profile has nothing tiered or owned. That is what an empty or wiped account looks\n' +
                  'like, not a sample. Check the account (or the file) and try again.');
    process.exit(1);
  }

  const titles = loadTitles();
  const unknown = unknownIds(profile, titles);
  if (unknown.length) {
    const list = unknown.map(u => '    ' + u.field.label + ': ' + u.id).join('\n');
    if (!flag('--drop-unknown')) {
      console.error('Refusing: ' + unknown.length + ' id(s) are not in the corpus, so they would be missing from the sample:\n' +
                    list + '\nRe-run with --drop-unknown to leave them out.');
      process.exit(1);
    }
    for (const u of unknown) {
      if (u.field.shape === 'list') profile[u.field.key] = profile[u.field.key].filter(id => String(id) !== u.id);
      else delete profile[u.field.key][u.id];
    }
    console.log('Left out ' + unknown.length + ' id(s) not in the corpus:\n' + list);
  }

  let before = {};
  try { before = readSampleFile(); } catch (e) { /* first run: nothing to compare against */ }
  const source = got.source + ' (' + new Date().toISOString().slice(0, 10) + ')';
  console.log('PK Sample from ' + source + ':\n' + describeChanges(before, profile, titles).join('\n'));
  if (flag('--dry-run')) { console.log('\n--dry-run: nothing written.'); return; }
  fs.writeFileSync(SAMPLE_FILE, renderSampleFile(profile, source));
  console.log('\nWrote ' + path.relative(ROOT, SAMPLE_FILE) + '. Run `npm run validate-corpus`, then commit it.');
}

if (require.main === module) main().catch(e => { console.error(e.message || e); process.exit(1); });
module.exports = { ID_FIELDS, idsOf, loadTitles, unknownIds, readSampleFile, profileFromFile, profileFromCloud };
