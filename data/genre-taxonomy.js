// Shared reference data - identical for everyone who opens the app, and independent of any
// one person's profile.
//
// GENRE TAXONOMY: every genre tag in the corpus, mapped to the canonical tags it inherits from.
//
// This exists to end substring matching on genres, which has caused two real defects in this
// repo (200 prose novels certified as poetry; one tag collecting two boosts at once). But a
// naive exact match is not the fix either -- it would silently break subgenre inheritance, so
// boosting "Horror" would stop lifting Body Horror, Folk Horror and Gothic Horror works. That
// is worse than the bug.
//
// So inheritance is declared rather than inferred. A boost or a filter keyed to Horror matches
// any tag whose list contains Horror -- exactly once, by lookup, with no accidental hits from
// unrelated words that happen to share letters.
//
// Each entry includes ITSELF, so a lookup never needs a special case for canonical tags.
// Every value is itself a real tag in the corpus: a parent nothing carries would be a boost
// target that can never match.
//
// Two kinds of parent are recorded here, and the second is why this is a data file rather than
// a function. Lexical: "War Drama" contains War and Drama, which a machine can see. Semantic:
// Sitcom is Comedy, Slasher is Horror, JRPG is RPG -- relationships nothing in the spelling
// reveals. Lexical decomposition alone also gets things actively wrong, which is why
// "Time Travel" maps to Sci-Fi and not to Travel.
//
// scripts/validate-corpus.js fails if any genre in data/*.js is missing from this file, so a
// new tag cannot enter the corpus without declaring what it inherits from.

// VIRTUAL ROOTS: canonical concepts that are valid boost and filter targets but that no work
// carries as a tag of its own. "Time" is the case that proved these are needed -- boosting it
// is a coherent taste, and Time Loop / Time Travel are how this corpus expresses it, but
// nothing is tagged plain "Time". Requiring every parent to be a real tag dropped the concept
// and silently cost Outer Wilds, Majora's Mask, Chrono Trigger, Into the Breach and The End
// of Eternity their boost -- caught by the snapshot diff before it shipped.
